#!/usr/bin/env python3
"""Generate the proxy-wasm export shims (exports.mbt) and the wasm link section
of moon.pkg for plugin packages. Other entries in moon.pkg, including other
`options(...)` keys such as `targets`, are kept.

  python3 scripts/gen_exports.py              # every package under examples/
  python3 scripts/gen_exports.py path/to/pkg  # your own plugin package(s)
  python3 scripts/gen_exports.py --check      # CI: fail if anything is stale
"""
import pathlib, re, sys

# (export name, params, returns, sdk function)
EXPORTS = [
    ("proxy_abi_version_0_2_1", [], None, None),
    ("proxy_on_memory_allocate", ["size"], "Int", "memory_allocate"),
    ("proxy_on_context_create", ["context_id", "parent_id"], None, "abi_on_context_create"),
    ("proxy_on_vm_start", ["context_id", "config_size"], "Int", "abi_on_vm_start"),
    ("proxy_on_configure", ["context_id", "config_size"], "Int", "abi_on_configure"),
    ("proxy_on_tick", ["context_id"], None, "abi_on_tick"),
    ("proxy_on_queue_ready", ["context_id", "queue_id"], None, "abi_on_queue_ready"),
    ("proxy_on_done", ["context_id"], "Int", "abi_on_done"),
    ("proxy_on_log", ["context_id"], None, "abi_on_log"),
    ("proxy_on_delete", ["context_id"], None, "abi_on_delete"),
    ("proxy_on_request_headers", ["context_id", "num_headers", "end_of_stream"], "Int", "abi_on_request_headers"),
    ("proxy_on_request_body", ["context_id", "body_size", "end_of_stream"], "Int", "abi_on_request_body"),
    ("proxy_on_request_trailers", ["context_id", "num_trailers"], "Int", "abi_on_request_trailers"),
    ("proxy_on_response_headers", ["context_id", "num_headers", "end_of_stream"], "Int", "abi_on_response_headers"),
    ("proxy_on_response_body", ["context_id", "body_size", "end_of_stream"], "Int", "abi_on_response_body"),
    ("proxy_on_response_trailers", ["context_id", "num_trailers"], "Int", "abi_on_response_trailers"),
    ("proxy_on_new_connection", ["context_id"], "Int", "abi_on_new_connection"),
    ("proxy_on_downstream_data", ["context_id", "data_size", "end_of_stream"], "Int", "abi_on_downstream_data"),
    ("proxy_on_downstream_connection_close", ["context_id", "peer_type"], None, "abi_on_downstream_connection_close"),
    ("proxy_on_upstream_data", ["context_id", "data_size", "end_of_stream"], "Int", "abi_on_upstream_data"),
    ("proxy_on_upstream_connection_close", ["context_id", "peer_type"], None, "abi_on_upstream_connection_close"),
    ("proxy_on_http_call_response", ["context_id", "token", "num_headers", "body_size", "num_trailers"], None, "abi_on_http_call_response"),
]

def shim():
    out = ["// Generated by scripts/gen_exports.py. Do not edit.",
           "// proxy-wasm ABI v0.2.1 entry points; each forwards to the SDK.", ""]
    for name, params, ret, target in EXPORTS:
        sig = ", ".join(f"{p} : Int" for p in params)
        out.append("///|")
        if target is None:
            out.append(f"pub fn {name}() -> Unit {{")
            out.append("  ()")
        else:
            r = f" -> {ret}" if ret else " -> Unit"
            out.append(f"pub fn {name}({sig}){r} {{")
            out.append(f"  @moonproxy.{target}({', '.join(params)})")
        out.append("}")
        out.append("")
    return "\n".join(out)

def link_entry(indent="  "):
    names = "".join(f'{indent}      "{n}",\n' for n, *_ in EXPORTS)
    return (f'{indent}link: {{\n{indent}  "wasm": {{\n{indent}    "exports": [\n' + names +
            f'{indent}    ],\n{indent}    "export-memory-name": "memory",\n{indent}  }},\n{indent}}},\n')

def match_close(text, i):
    """Index just past the bracket that closes text[i] (skipping strings)."""
    depth, in_str = 0, False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise SystemExit("unbalanced brackets in moon.pkg")

def with_link(pkg):
    """moon.pkg text with the wasm link entry set, other options kept."""
    start = pkg.find("options(")
    if start < 0:
        return pkg.rstrip() + "\n\noptions(\n" + link_entry() + ")\n"
    open_paren = start + len("options")
    end = match_close(pkg, open_paren)
    body = pkg[open_paren + 1:end - 1]
    m = re.search(r'(^|\n)([ \t]*)link\s*:\s*\{', body)
    if m:
        brace = m.end() - 1
        stop = match_close(body, brace)
        if body[stop:stop + 1] == ",":
            stop += 1
        if body[stop:stop + 1] == "\n":
            stop += 1
        line_start = m.start() + (1 if m.group(1) else 0)
        body = body[:line_start] + link_entry() + body[stop:]
    else:
        if not body.endswith("\n"):
            body = body.rstrip() + "\n"
        if body.strip() and not body.rstrip().endswith(","):
            body = body.rstrip() + ",\n"
        body = body + link_entry()
    return pkg[:open_paren + 1] + body + pkg[end - 1:]

def main():
    check = "--check" in sys.argv
    dirs = [pathlib.Path(a) for a in sys.argv[1:] if not a.startswith("--")]
    if not dirs:
        dirs = sorted(p for p in pathlib.Path("examples").iterdir() if (p / "moon.pkg").exists())
    stale = []
    for d in dirs:
        want = {d / "exports.mbt": shim()}
        want[d / "moon.pkg"] = with_link((d / "moon.pkg").read_text())
        for path, text in want.items():
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
                if not check:
                    path.write_text(text)
    if check and stale:
        print("out of date, run scripts/gen_exports.py:", *stale, sep="\n  ")
        sys.exit(1)

if __name__ == "__main__":
    main()
